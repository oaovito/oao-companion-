// A parte do corpo que a peça do visual já ocupa fica livre na fantasia.
const LIVRE = { cabeca: 'cabeca', rosto: 'rosto', pescoco: 'pescoco', mao: 'mao', bermuda: 'baixo' };

/** Fantasia completa e show (gesto e efeito) de um visual; null se não tiver. */
export function showDoVisual(id, parte) {
  const linha = S[id];
  if (!linha) return null;
  const [roupa, acao] = linha.split('|').map((x) => x.trim().split(/\s+/));
  const v = (x) => (x === '-' ? null : x);
  const [tronco, mangas, baixo, pes, cabeca, rosto, pescoco, mao, estampa] = roupa.map(v);
  const fantasia = {
    tronco: tronco || 'camiseta', mangas, baixo: baixo || 'nenhum', pes: pes || 'descalco', cabeca: cabeca || 'nenhuma',
    rosto: rosto ? rosto.split('+') : [], pescoco: pescoco || 'nenhum', mao: mao || 'nenhum', estampa,
  };
  const livre = LIVRE[parte];
  if (livre === 'cabeca') fantasia.cabeca = 'nenhuma';
  if (livre === 'rosto') fantasia.rosto = [];
  if (livre === 'pescoco') fantasia.pescoco = 'nenhum';
  if (livre === 'mao') fantasia.mao = 'nenhum';
  if (livre === 'baixo') fantasia.baixo = null; // a bermuda do visual é a parte de baixo
  return { fantasia, gesto: acao[0], efeito: acao[1] };
}

